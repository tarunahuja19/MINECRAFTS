"""C2: deterministic scripted runs, offline and through the live session.

The real default_demo is 8,760 hourly ticks (~3 minutes), so the run tests use
a 30-day copy of it with the same four events squeezed into days 5-20.

Run from `simulation/`:
    .venv/bin/python -m pytest tests/test_scripted_run.py -q
"""

import csv
import hashlib
import json
from datetime import datetime, timedelta

import pytest
from starlette.testclient import TestClient

from sandbox import constants
from sandbox.runner import run_script_offline
from sandbox.script import SCENARIO_DIR, load_script, parse_script
from sandbox.server import app, get_session
from sandbox.session import SessionConfig, SimulationSession

SHORT_DAYS = {"crack": 5, "tilt": 12, "vibration": 15, "cave_in": 20}


def _short_script():
    raw = json.loads((SCENARIO_DIR / "default_demo.json").read_text())
    raw["name"] = "short_demo"
    raw["duration_days"] = 30
    for ev in raw["events"]:
        ev["day"] = SHORT_DAYS[ev["type"]]
    return parse_script(raw)


@pytest.fixture(scope="module")
def two_runs(tmp_path_factory):
    script = _short_script()
    root = tmp_path_factory.mktemp("scripted")
    return script, run_script_offline(script, root / "a"), run_script_offline(script, root / "b"), root


def _rows(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def _t(iso):
    return datetime.fromisoformat(iso.replace("Z", "+00:00"))


def test_offline_twice_gives_identical_files(two_runs):
    _, a, b, root = two_runs
    assert a == b
    for name, digest in a.items():
        assert digest == hashlib.sha256((root / "a" / name).read_bytes()).hexdigest()
        print(f"sha256 {name} {digest}")


def test_offline_output_shape(two_runs):
    script, _, _, root = two_runs
    lines = (root / "a" / "nodes.csv").read_text().splitlines()
    assert lines[0].startswith("# GENERATED BY SIMULATOR")
    assert f"scenario={script.name} seed={script.seed}" in lines[0]
    assert len(lines) == 2 + script.n_ticks * 31
    assert lines[2].startswith("2026-01-01T00:00:00Z,")
    assert lines[-1].startswith("2026-01-30T23:00:00Z,")


def test_each_event_fires_once_on_its_day(two_runs):
    script, _, _, root = two_runs
    rows = [r for r in _rows(root / "a" / "events.csv") if r["kind"] != "zone_transition"]
    base = _t(script.base_iso_time)
    fired = {r["kind"]: r for r in rows if r["kind"] in ("crack", "tilt", "blast", "collapse")}
    assert sorted(fired) == ["blast", "collapse", "crack", "tilt"]
    assert sum(r["kind"] in fired for r in rows) == 4
    for kind, ev in zip(("crack", "tilt", "blast", "collapse"), script.events):
        assert _t(fired[kind]["t_iso"]) == base + timedelta(days=ev["day"])


def test_first_alarm_of_each_ring_event_lands_within_one_packet(two_runs):
    script, _, _, root = two_runs
    rows = _rows(root / "a" / "events.csv")
    alarms = [r for r in rows if r["kind"] == "node_alarm"]
    base = _t(script.base_iso_time)
    for kind, ev in (("crack", script.events[0]), ("collapse", script.events[3])):
        at = base + timedelta(days=ev["day"])
        first = min((_t(a["t_iso"]) for a in alarms if _t(a["t_iso"]) >= at), default=None)
        assert first is not None, f"no alarm after the {kind}"
        assert timedelta(0) <= first - at <= timedelta(seconds=script.tick_seconds), (kind, first - at)
    notes = {a["note"].split()[1] for a in alarms}
    assert notes == {"WARNING", "CRITICAL"}


def test_tilt_alarms_come_from_the_tilt_not_a_ring(two_runs):
    script, _, _, root = two_runs
    base = _t(script.base_iso_time)
    start, end = (base + timedelta(days=d) for d in (12, 20))
    alarms = [r for r in _rows(root / "a" / "events.csv")
              if r["kind"] == "node_alarm" and start <= _t(r["t_iso"]) < end]
    assert alarms and all(a["note"].endswith("WARNING") for a in alarms)


def test_packets_follow_the_script_tick(tmp_path):
    script = _short_script()
    s = SimulationSession(SessionConfig(out_dir=tmp_path, save_packet_json=False))
    s.mqtt_bridge.enabled = False
    s.load_script(script)
    assert s.packet_aggregator.session_id == "short_demo"
    s.start()
    ids = []
    for _ in range(3):
        payload = s.tick()
        assert payload["packet_available"]
        ids.append(s.last_finalized_packet["end_sim_time"] - s.last_finalized_packet["start_sim_time"])
    s.stop()
    assert ids == [script.tick_seconds] * 3


def test_load_script_refused_while_running_and_reset_unloads(tmp_path):
    s = SimulationSession(SessionConfig(out_dir=tmp_path, save_packet_json=False, seed=7))
    s.mqtt_bridge.enabled = False
    s.start()
    with pytest.raises(RuntimeError, match="running"):
        s.load_script(_short_script())
    s.stop()
    s.load_script(_short_script())
    assert s.config.seed == 20260927 and s.config.auto_snap_speed is False
    assert len(s._pending_script_events) == 4
    s.reset()
    assert s.script is None and s._pending_script_events == []
    assert (s.config.seed, s.config.tick_duration_sim_s) == (7, constants.TICK_SIM_SECONDS)
    assert s.packet_aggregator.window_duration_sim_s == constants.TICK_SIM_SECONDS


