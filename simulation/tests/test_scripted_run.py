@pytest.fixture
def live():
    session = get_session()
    session.reset()
    session.mqtt_bridge.enabled = False
    with TestClient(app) as client:
        yield client, session
    session.reset()


def test_script_run_loads_the_live_session(live):
    client, session = live
    res = client.post("/script/run", json={"name": "default_demo"})
    assert res.status_code == 200
    body = res.json()
    assert (body["status"], body["name"], body["n_ticks"]) == ("loaded", "default_demo", 8760)
    assert [e["type"] for e in body["events"]] == ["crack", "tilt", "vibration", "cave_in"]
    assert session.script is not None and not session.is_running
    assert session.speed_multiplier == pytest.approx(body["speed"])


def test_script_run_refused_while_running(live):
    client, session = live
    session.start()
    res = client.post("/script/run", json={"name": "default_demo"})
    assert res.status_code == 409
    assert session.script is None
    session.stop()


